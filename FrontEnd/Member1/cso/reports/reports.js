function renderReportsTable() {
    const tableBody = document.getElementById("reports-table-body");
    if (!tableBody) return;

    tableBody.innerHTML = "";

    departmentReportsData.forEach((report) => {
        const row = document.createElement("tr");

        let statusBadgeClass = "severity-low";
        let iconClass = "fa-circle-dot";

        const normalizedStatus = (report.status || "Received").toLowerCase();

        if (normalizedStatus === "reviewed" || normalizedStatus === "approved") {
            statusBadgeClass = "severity-medium";
            iconClass = "fa-circle-check";
        } else if (normalizedStatus === "pending") {
            statusBadgeClass = "severity-high";
            iconClass = "fa-clock";
        }

        row.innerHTML = `
      <td>
        <strong>#${report.id}</strong><br>
        <small style="color: var(--text-muted);">${report.title}</small>
      </td>
      <td>${report.dept}</td>
      <td>${report.oicName}</td>
      <td>${report.date}</td>
      <td><span class="sev-badge ${statusBadgeClass}"><i class="fa-solid ${iconClass}"></i> ${report.status}</span></td>
      <td class="text-right">
        <div class="action-btns">
          <button class="btn-icon" title="View Report" onclick="viewReport('${report.id}', 'dept')"><i class="fa-solid fa-eye"></i></button>
          <button class="btn-icon" title="Download File" onclick="downloadReport('${report.id}')"><i class="fa-solid fa-download"></i></button>
        </div>
      </td>
    `;
        tableBody.appendChild(row);
    });
}

