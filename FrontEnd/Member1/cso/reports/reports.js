function openGenerateModal() {
    const form = document.getElementById("generateReportForm");
    if (form) form.reset();

    const today = new Date().toISOString().split('T')[0];
    const lastMonth = new Date(Date.now() - 30 * 24 * 60 * 60 * 1000).toISOString().split('T')[0];

    const startDateInput = document.getElementById("report-start-date");
    const endDateInput = document.getElementById("report-end-date");

    if (startDateInput) startDateInput.value = lastMonth;
    if (endDateInput) endDateInput.value = today;

    const modal = document.getElementById("generateReportModal");
    if (modal) modal.classList.add("active");
}

function closeModal(modalId) {
    const modal = document.getElementById(modalId);
    if (modal) modal.classList.remove("active");
}

function handleGenerateSummaryReport(event) {
    event.preventDefault();

    const title = document.getElementById("report-title").value;
    const notes = document.getElementById("report-notes").value;

    const newId = `SUM-2026-${Math.floor(100 + Math.random() * 900)}`;
    const today = new Date().toISOString().split('T')[0];

    const newSummaryReport = {
        id: newId,
        title: title,
        recipient: "University Administrator",
        date: today,
        status: "Sent to Admin",
        summary: notes
    };

    summaryReportsData.unshift(newSummaryReport);
    renderSummaryTable();
    updateMetrics();
    closeModal("generateReportModal");

    alert(`Summary Report #${newId} compiled and sent to University Administrator successfully!`);
}

/* ==========================================
   VIEW & DOWNLOAD ACTIONS
   ========================================== */
function viewReport(reportId, type = 'dept') {
    let report = null;

    if (type === 'summary') {
        report = summaryReportsData.find((r) => r.id === reportId);
    } else {
        report = departmentReportsData.find((r) => r.id === reportId);
    }

    if (!report) return;

    const titleEl = document.getElementById("viewReportTitle");
    const idEl = document.getElementById("view-report-id");
    const summaryEl = document.getElementById("view-report-summary");

    if (titleEl) titleEl.textContent = report.title;
    if (idEl) idEl.value = `#${report.id} [${report.status}]`;
    if (summaryEl) summaryEl.value = report.summary;

    const modal = document.getElementById("viewReportModal");
    if (modal) modal.classList.add("active");
}

